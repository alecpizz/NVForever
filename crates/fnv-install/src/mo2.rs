    #[test]
    fn settings_ini_decides_local_saves_and_ini_copies() {
        let t = std::env::temp_dir().join(format!("nvf-mo2-settings-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&t);
        let l = Layout { mods: t.join("mods"), overwrite: t.join("overwrite"), profile: t.join("profiles/P") };
        std::fs::create_dir_all(&l.profile).unwrap();
        // No settings.ini and no saves folder: the player's own folder is used.
        assert!(!l.local_saves());
        assert_eq!(l.saves_dir(), None);
        // A saves folder with no key: MO2's findProfileSettings reads that as on.
        std::fs::create_dir_all(l.profile.join("saves")).unwrap();
        assert!(l.local_saves());
        assert_eq!(l.saves_dir(), Some(l.profile.join("saves")));
        // The key beats the folder, both ways.
        std::fs::write(l.profile.join("settings.ini"), "[General]\r\nLocalSaves=false\r\n").unwrap();
        assert!(!l.local_saves());
        assert_eq!(l.saves_dir(), None);
        std::fs::write(l.profile.join("settings.ini"), "[General]\r\nLocalSaves=true\r\n").unwrap();
        assert!(l.local_saves());
        // Local settings: off until a Fallout.ini is there, since MO2's copies exist only
        // with them on; the key decides too.
        assert!(!l.local_settings());
        assert!(l.profile_inis().is_empty());
        std::fs::write(l.profile.join("falloutprefs.ini"), "[Display]\r\niSize W=1280\r\n").unwrap();
        assert!(!l.local_settings());
        std::fs::write(l.profile.join("Fallout.ini"), "[General]\r\nuGridsToLoad=5\r\n").unwrap();
        assert!(l.local_settings());
        assert_eq!(l.profile_inis(), vec![l.profile.join("Fallout.ini"), l.profile.join("falloutprefs.ini")]);
        std::fs::write(l.profile.join("settings.ini"), "[General]\r\nLocalSaves=true\r\nLocalSettings=false\r\n").unwrap();
        assert!(!l.local_settings());
        assert!(l.profile_inis().is_empty());
        std::fs::remove_dir_all(&t).ok();
    }

    #[test]
    fn ini_texts_lay_the_tweaks_above_the_profile_inis() {
        let t = std::env::temp_dir().join(format!("nvf-mo2-inis-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&t);
        let l = Layout { mods: t.join("mods"), overwrite: t.join("overwrite"), profile: t.join("profiles/P") };
        std::fs::create_dir_all(&l.profile).unwrap();
        // Nothing at all: no text, no setting.
        assert!(l.ini_texts().is_empty());
        assert_eq!(l.ini_setting("Display", "iSize W"), None);
        std::fs::write(l.profile.join("Fallout.ini"), "[General]\r\nuGridsToLoad=5\r\n[Display]\r\niSize W=1280\r\n").unwrap();
        std::fs::write(l.profile.join("FalloutPrefs.ini"), "[Display]\r\niSize H=720\r\n").unwrap();
        // MO2's tweak file: mods' INI tweaks and the profile's own, merged, above both INIs.
        std::fs::write(l.profile.join("initweaks.ini"), "[Display]\r\niSize W=1920\r\n[Archive]\r\nbInvalidateOlderFiles=1\r\n").unwrap();
        assert_eq!(
            l.ini_texts().into_iter().map(|(p, _)| p).collect::<Vec<_>>(),
            vec![l.profile.join("Fallout.ini"), l.profile.join("FalloutPrefs.ini"), l.profile.join("initweaks.ini")]
        );
        assert_eq!(l.ini_setting("Display", "iSize W"), Some(("1920".into(), l.profile.join("initweaks.ini"))));
        assert_eq!(l.ini_setting("Display", "iSize H"), Some(("720".into(), l.profile.join("FalloutPrefs.ini"))));
        assert_eq!(l.ini_setting("General", "uGridsToLoad"), Some(("5".into(), l.profile.join("Fallout.ini"))));
        assert_eq!(l.ini_setting("Archive", "bInvalidateOlderFiles"), Some(("1".into(), l.profile.join("initweaks.ini"))));
        // FalloutCustom.ini, the user's overrides, after the two INIs and under the tweaks (#4491).
        std::fs::write(l.profile.join("FalloutCustom.ini"), "[BackgroundLoad]\r\nbBackgroundLoadLipFiles=1\r\n[Display]\r\niSize H=1080\r\n").unwrap();
        assert_eq!(l.ini_setting("BackgroundLoad", "bBackgroundLoadLipFiles"), Some(("1".into(), l.profile.join("FalloutCustom.ini"))));
        assert_eq!(l.ini_setting("Display", "iSize H"), Some(("1080".into(), l.profile.join("FalloutCustom.ini"))));
        assert_eq!(l.ini_setting("Display", "iSize W"), Some(("1920".into(), l.profile.join("initweaks.ini"))));
        std::fs::remove_file(l.profile.join("FalloutCustom.ini")).unwrap();
        // A profile with local settings off still reads the tweak file, which MO2 keeps in
        // the profile whatever the INIs' setting is.
        std::fs::write(l.profile.join("settings.ini"), "[General]\r\nLocalSettings=false\r\n").unwrap();
        assert_eq!(l.ini_texts().into_iter().map(|(p, _)| p).collect::<Vec<_>>(), vec![l.profile.join("initweaks.ini")]);
        assert_eq!(l.ini_setting("General", "uGridsToLoad"), None);
        std::fs::remove_dir_all(&t).ok();
    }
