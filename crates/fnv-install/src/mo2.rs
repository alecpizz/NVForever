/// The first line MO2 writes in the lists it makes.
pub const HEADER: &str = "# This file was automatically generated by Mod Organizer.";

/// The instance's settings file.
pub const INI_FILE: &str = "ModOrganizer.ini";

/// The profile's own settings file, `settings.ini` in the profile folder.
pub const PROFILE_SETTINGS: &str = "settings.ini";

/// The game INI files a profile keeps a copy of when its local settings are on, in the
/// order the game reads them: `Fallout.ini`, then `FalloutPrefs.ini` (a key in both is the
/// prefs file's) [documented: MO2 `IPluginGame::iniFiles` for the Gamebryo games; observed:
/// both files in the owner's profiles]. Then `FalloutCustom.ini`, the user's overrides,
/// read last [observed: Nuclear Sunset's profile keeps one, `[BackgroundLoad]
/// bBackgroundLoadLipFiles=1` over Fallout.ini's 0, and TTW's start check
/// `GetNumericIniSetting "bBackgroundLoadLipFiles:BackgroundLoad" == 0` shows
/// TTWBadINIMessage without it, log nvforever-20261125-155959-14680.log; hypothesis: the
/// game reads it after the other two].
pub const PROFILE_INIS: [&str; 3] = ["Fallout.ini", "FalloutPrefs.ini", "FalloutCustom.ini"];

/// The file MO2 writes the enabled mods' INI tweaks into, above the profile's own INIs
/// [documented: MO2 `Profile::createTweakedIniFile`].
pub const TWEAKS_INI: &str = "initweaks.ini";

/// The usvfs DLL MO2 injects into a 64-bit program.
pub const USVFS_DLL: &str = "usvfs_x64.dll";

/// Whether usvfs is loaded in this process, i.e. MO2 (or another usvfs user) started it.
#[cfg(windows)]
pub fn usvfs_loaded() -> bool {
    #[link(name = "kernel32")]
    extern "system" {
        fn GetModuleHandleW(name: *const u16) -> *mut core::ffi::c_void;
    }
    let name: Vec<u16> = USVFS_DLL.encode_utf16().chain(std::iter::once(0)).collect();
    // SAFETY: a NUL-terminated UTF-16 name; GetModuleHandleW takes no reference and the
    // handle is only compared with null.
    !unsafe { GetModuleHandleW(name.as_ptr()) }.is_null()
}

#[cfg(not(windows))]
pub fn usvfs_loaded() -> bool {
    false
}

#[cfg(windows)]
mod win {
    use std::ffi::{c_void, OsString};
    use std::os::windows::ffi::{OsStrExt, OsStringExt};
    use std::path::PathBuf;

    #[link(name = "kernel32")]
    extern "system" {
        fn GetModuleHandleW(name: *const u16) -> *mut c_void;
        fn GetModuleFileNameW(module: *mut c_void, buf: *mut u16, size: u32) -> u32;
    }
    #[link(name = "advapi32")]
    extern "system" {
        fn RegGetValueW(key: isize, sub: *const u16, value: *const u16, flags: u32, ty: *mut u32, data: *mut c_void, len: *mut u32) -> i32;
    }
    const HKEY_CURRENT_USER: isize = 0x8000_0001_u32 as i32 as isize;
    const RRF_RT_REG_SZ: u32 = 0x2;

    fn wide(s: &str) -> Vec<u16> {
        std::ffi::OsStr::new(s).encode_wide().chain(std::iter::once(0)).collect()
    }

    /// The file a loaded module of this process was loaded from.
    pub fn module_path(name: &str) -> Option<PathBuf> {
        let n = wide(name);
        // SAFETY: NUL-terminated name; the handle is used only while the module is loaded
        // (usvfs stays loaded for the process' life) and the buffer's length is passed.
        unsafe {
            let h = GetModuleHandleW(n.as_ptr());
            if h.is_null() {
                return None;
            }
            let mut buf = vec![0u16; 32768];
            let len = GetModuleFileNameW(h, buf.as_mut_ptr(), buf.len() as u32) as usize;
            (len > 0 && len < buf.len()).then(|| PathBuf::from(OsString::from_wide(&buf[..len])))
        }
    }

    /// A REG_SZ value under HKEY_CURRENT_USER.
    pub fn user_string(sub: &str, value: &str) -> Option<String> {
        let (s, v) = (wide(sub), wide(value));
        let mut buf = vec![0u16; 4096];
        let mut len = (buf.len() * 2) as u32;
        // SAFETY: NUL-terminated names; the buffer's size in bytes is passed and written back.
        let r = unsafe {
            RegGetValueW(HKEY_CURRENT_USER, s.as_ptr(), v.as_ptr(), RRF_RT_REG_SZ, std::ptr::null_mut(), buf.as_mut_ptr().cast(), &mut len)
        };
        if r != 0 {
            return None;
        }
        let n = (len as usize / 2).min(buf.len());
        let end = buf[..n].iter().position(|&c| c == 0).unwrap_or(n);
        Some(String::from_utf16_lossy(&buf[..end]))
    }
}

/// The folder of the MO2 instance that started this process, or `None` when MO2 did not
/// (module notes).
#[cfg(windows)]
pub fn instance_dir() -> Option<PathBuf> {
    let app = win::module_path(USVFS_DLL)?.parent()?.to_path_buf();
    let current = win::user_string(r"Software\Mod Organizer Team\Mod Organizer", "CurrentInstance").unwrap_or_default();
    let global = directories::BaseDirs::new().map(|d| d.data_local_dir().join("ModOrganizer"));
    pick_instance(&app, &current, global.as_deref())
}

#[cfg(not(windows))]
pub fn instance_dir() -> Option<PathBuf> {
    None
}

/// MO2's choice of instance: `app` is `ModOrganizer.exe`'s folder, `current` the
/// registry's `CurrentInstance`, `global` the folder of global instances.
#[cfg_attr(not(windows), allow(dead_code))]
fn pick_instance(app: &std::path::Path, current: &str, global: Option<&std::path::Path>) -> Option<PathBuf> {
    if app.join("portable.txt").is_file() {
        return Some(app.to_path_buf());
    }
    if !current.is_empty() {
        return global.map(|g| g.join(current));
    }
    app.join("ModOrganizer.ini").is_file().then(|| app.to_path_buf())
}

/// The value of `key` under `[section]` of an MO2 `ModOrganizer.ini`: `@ByteArray(...)`
/// unwrapped and `\\` read as `\` (Qt's escaping), or a plain value as it is. `None` when
/// absent or empty. Qt's escapes are read ([`qt_unescape`]).
pub fn ini_value(ini: &str, section: &str, key: &str) -> Option<String> {
    let header = format!("[{section}]");
    let mut inside = false;
    for line in ini.lines() {
        let t = line.trim();
        if t.starts_with('[') {
            inside = t.eq_ignore_ascii_case(&header);
            continue;
        }
        let Some((k, v)) = t.split_once('=').filter(|_| inside) else { continue };
        if !k.trim().eq_ignore_ascii_case(key) {
            continue;
        }
        let v = v.trim();
        let (v, bytes) = match v.strip_prefix("@ByteArray(").and_then(|r| r.strip_suffix(')')) {
            Some(inner) => (inner, true),
            None => (v, false),
        };
        let out = qt_unescape(v, bytes);
        return (!out.is_empty()).then_some(out);
    }
    None
}

/// `gamePath` under `[General]` of an MO2 `ModOrganizer.ini`.
pub fn ini_game_path(ini: &str) -> Option<PathBuf> {
    ini_value(ini, "General", "gamePath").map(PathBuf::from)
}

/// The folders of an MO2 instance that a save goes into (docs/design/editor.md §4.1,
/// owner 2026-11-01: under MO2 a save goes into the plugin being edited, else MO2's
/// overwrite folder).
///
/// From `ModOrganizer.ini` [documented: MO2 `PathSettings`]: `base_directory`,
/// `mod_directory`, `overwrite_directory` and `profiles_directory` under `[Settings]`,
/// each defaulting to `%BASE_DIR%/mods`, `%BASE_DIR%/overwrite` and `%BASE_DIR%/profiles`,
/// `%BASE_DIR%` itself defaulting to the instance's folder; the profile is
/// `selected_profile` under `[General]`. Neither of the owner's instances sets the folders
/// [observed: F:\Modlists\VNV and F:\Modding\MO2, 2026-11-01: `mods`, `overwrite` and
/// profiles` beside the INI]. MO2 itself only substitutes `%BASE_DIR%` [documented:
/// `PathSettings::resolve`]; a relative folder is joined onto the instance's folder here
/// [hypothesis].
#[derive(Debug, Clone, PartialEq)]
pub struct Layout {
    pub mods: PathBuf,
    pub overwrite: PathBuf,
    /// The selected profile's folder (`modlist.txt`, `plugins.txt`, `loadorder.txt`).
    pub profile: PathBuf,
}

// Nearly the same struct as Layout but semantically different: a profile has not been chosen yet from the profiles directory
struct BaseLayout {
    mods: PathBuf,
    overwrite: PathBuf,
    profiles_dir: PathBuf,
    selected_profile: Option<String>
}

impl Layout {
    /// The layout of the instance in `instance`, whose `ModOrganizer.ini` reads `ini`.
    pub fn from_ini(instance: &Path, ini: &str) -> Option<Layout> {
        let base = Self::base_layout_from_ini_profile(instance, ini);
        if let Some(profile) = base.selected_profile {
            let path = base.profiles_dir.join(profile);
            Some(Layout { mods: base.mods, overwrite: base.overwrite, profile: path })
        } else {
            None
        }
    }

    /// [`Layout::from_ini`] with a profile named instead of the instance's
    /// `selected_profile` (`--profile`; issue #1526).
    fn base_layout_from_ini_profile(instance: &Path, ini: &str) -> BaseLayout {
        // An instance given relative (a test aid's) is made absolute first, so that a
        // `%BASE_DIR%` holding it is not joined onto it a second time.
        let instance = &std::path::absolute(instance).unwrap_or_else(|_| instance.to_path_buf());
        let at = |s: String, base: &Path| -> PathBuf {
            let s = s.replace("%BASE_DIR%", &base.to_string_lossy());
            let p = PathBuf::from(s);
            if p.is_absolute() {
                p
            } else {
                instance.join(p)
            }
        };
        let base = ini_value(ini, "Settings", "base_directory").map_or_else(|| instance.to_path_buf(), |b| at(b, instance));
        let dir = |key: &str, default: &str| at(ini_value(ini, "Settings", key).unwrap_or_else(|| format!("%BASE_DIR%/{default}")), &base);
        let selected_profile = ini_value(ini, "General", "selected_profile");
        BaseLayout { mods: dir("mod_directory", "mods"), overwrite: dir("overwrite_directory", "overwrite"), profiles_dir: dir("profiles_directory", "profiles"), selected_profile }
    }

    // Create a BaseLayout directly from a base_directory instead of an instance
    fn base_layout_from_base_directory(dir: &Path) -> BaseLayout {
        let mods = dir.join("mods");
        let overwrite = dir.join("overwrite");
        let profiles_dir = dir.join("profiles");

        BaseLayout { mods, overwrite, profiles_dir, selected_profile: None }
    }

    // Get a reasonable profile name from the profiles directory
    pub fn get_default_profile(profiles_dir: &Path) -> Option<String> {
        // If the profiles dir has only one dir inside of it, return that
        if let Ok(dirs) = profiles_dir.read_dir() {
            let mut dirs = dirs.flatten().filter(|e| e.file_type().is_ok_and(|e| e.is_dir()));
            if let Some(dir) = dirs.next() {
                if dirs.next().is_none() {
                    return Some(dir.file_name().to_string_lossy().to_string());
                }
            }
        }

        // If the profiles dir has more than one dir inside of it, but it has a Default profile, return that
        let default = profiles_dir.join("Default");
        if default.exists() && default.is_dir() {
            return Some("Default".to_string());
        }
        None
    }

    /// The layout of the instance that started this process (`None` when MO2 did not).
    pub fn current() -> Option<Layout> {
        if !usvfs_loaded() {
            return None;
        }
        Self::of_instance(&instance_dir()?)
    }

    /// The layout of the instance in folder `instance`.
    pub fn of_instance(instance: &Path) -> Option<Layout> {
        Self::open(instance, None).ok()
    }

    /// [`Layout::of_instance`] with a profile named instead of the instance's selected one
    /// (`--mo2 <instance> --profile <name>`, issue #1526), and the reason when the folder is
    /// not an instance or the profile is not there.
    pub fn open(instance: &Path, profile: Option<&str>) -> Result<Layout, InstallError> {
        let ini_path = instance.join(INI_FILE);
        let base = {
            if let Ok(ini) = std::fs::read_to_string(&ini_path) {
                Self::base_layout_from_ini_profile(instance, &ini)
            } else {
                Self::base_layout_from_base_directory(instance)
        }};

        if [base.mods.as_path(), base.overwrite.as_path(), base.profiles_dir.as_path()].iter().any(|p| !p.is_dir()) {
            return Err(InstallError::Config(format!("{} is not a valid Mod Organizer 2 instance (no {INI_FILE}), or base directory with 'mods', 'profiles', and 'overwrite' folders", instance.display())));
        }

        if let Some(profile) = profile {
            let path = base.profiles_dir.join(profile);
            if path.is_dir() {
                return Ok(Layout{mods: base.mods, overwrite: base.overwrite, profile: path})
            } else {
                return Err(InstallError::Config(format!("{}: no profile {profile}", base.profiles_dir.display())))
            }
        }

        if let Some(profile) = base.selected_profile {
            let path = base.profiles_dir.join(profile);
            if path.is_dir() {
                return Ok(Layout{mods: base.mods, overwrite: base.overwrite, profile: path})
            }
        }

        if let Some(profile) = Self::get_default_profile(&base.profiles_dir) {
            let path = base.profiles_dir.join(profile);
            if path.is_dir() {
                return Ok(Layout{mods: base.mods, overwrite: base.overwrite, profile: path})
            }
        }

        Err(InstallError::Config(format!("{}: no selected_profile; name one with --profile", base.profiles_dir.display())))
    }

    /// The profile's name (its folder's).
    pub fn profile_name(&self) -> String {
        self.profile.file_name().map_or_else(|| self.profile.display().to_string(), |n| n.to_string_lossy().into_owned())
    }

    /// The files' roots, lowest precedence first, as usvfs merges them over `Data`: the
    /// enabled mods from the lowest priority up, then the overwrite folder on top
    /// [documented: MO2 `Profile::doWriteModlist` writes the highest priority first;
    /// observed: the owner's profile]. Mods whose folder is absent are skipped (a list can
    /// outlive a deleted mod).
    pub fn mod_roots(&self) -> Vec<PathBuf> {
        let modlist = std::fs::read_to_string(self.profile.join("modlist.txt")).unwrap_or_default();
        let mut roots: Vec<PathBuf> = enabled_mods(&modlist)
            .into_iter()
            .rev()
            .map(|m| self.mods.join(m))
            .filter(|p| p.is_dir())
            .collect();
        if self.overwrite.is_dir() {
            roots.push(self.overwrite.clone());
        }
        roots
    }

    /// The profile's `plugins.txt`: the active plugins in load order, as MO2 writes it
    /// ([`parse`]).
    pub fn profile_plugins(&self) -> Result<Vec<String>, InstallError> {
        let path = self.profile.join("plugins.txt");
        let bytes = std::fs::read(&path).map_err(|e| InstallError::Io(path.clone(), e))?;
        parse(&bytes).ok_or_else(|| InstallError::Config(format!("{} is not an MO2 plugins list (no header line)", path.display())))
    }

    /// The `*.bsa` files the enabled mods hold at their root, highest priority first,
    /// without repeats: archives that a merge of loose files does not mount yet (#1526
    /// phase 1; the engine warns about them).
    pub fn mod_archives(&self) -> Vec<String> {
        let modlist = std::fs::read_to_string(self.profile.join("modlist.txt")).unwrap_or_default();
        let mut names: Vec<String> = Vec::new();
        for m in enabled_mods(&modlist) {
            let mut here: Vec<String> = std::fs::read_dir(self.mods.join(&m))
                .map(|rd| {
                    rd.flatten()
                        .map(|e| e.file_name().to_string_lossy().into_owned())
                        .filter(|n| n.to_ascii_lowercase().ends_with(".bsa"))
                        .collect()
                })
                .unwrap_or_default();
            here.sort();
            for n in here {
                if !names.iter().any(|o| o.eq_ignore_ascii_case(&n)) {
                    names.push(n);
                }
            }
        }
        names
    }

    /// The archives the profile has enabled, lowest precedence first, and the file the list
    /// came from: `archives.txt` (the Archives tab's ticked entries, one name per line
    /// [documented: MO2 `MainWindow::saveArchiveList`]) or, when that file is absent or
    /// empty, `[Archive] SArchiveList` of the profile's `fallout.ini` [documented:
    /// `FalloutNVDataArchives::archives`, which reads that key from the profile's INI when
    /// local settings are on]. `None` when neither names an archive, so a profile made by
    /// hand still starts with the shipped default list.
    pub fn profile_archives(&self) -> Option<(Vec<String>, PathBuf)> {
        let list = self.profile.join("archives.txt");
        if let Ok(text) = std::fs::read_to_string(&list) {
            let names: Vec<String> = text
                .lines()
                .map(str::trim)
                .filter(|l| !l.is_empty() && !l.starts_with('#'))
                .map(str::to_string)
                .collect();
            if !names.is_empty() {
                return Some((names, list));
            }
        }
        let ini = std::fs::read_dir(&self.profile).ok()?.flatten().map(|e| e.path()).find(|p| p.file_name().is_some_and(|f| f.to_string_lossy().eq_ignore_ascii_case("fallout.ini")))?;
        let text = std::fs::read_to_string(&ini).ok()?;
        let names: Vec<String> = ini_value(&text, "Archive", "SArchiveList")?
            .split(',')
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(str::to_string)
            .collect();
        (!names.is_empty()).then_some((names, ini))
    }

    /// A top-level key of the profile's `settings.ini`. QSettings writes a key outside
    /// any group under `[General]` [documented: Qt QSettings INI format; observed: MO2's
    /// profiles hold `LocalSaves` and `LocalSettings` there].
    pub fn profile_setting(&self, key: &str) -> Option<String> {
        let text = std::fs::read_to_string(self.profile.join(PROFILE_SETTINGS)).ok()?;
        ini_value(&text, "General", key)
    }

    /// Whether the profile keeps its own saves (`<profile>/saves`) instead of the
    /// player's folder [documented: MO2 `Profile::localSavesEnabled`, `settings.ini`'s
    /// `LocalSaves`]. A profile without the key is read as MO2's
    /// `Profile::findProfileSettings` reads it: a `saves` folder means on. MO2's global
    /// switch (`profile_local_saves`) is not visible here, so a profile with neither is
    /// off [hypothesis: the instance's own settings keep it; not read].
    pub fn local_saves(&self) -> bool {
        self.profile_setting("LocalSaves").map_or_else(|| self.profile.join("saves").is_dir(), |v| bool_value(&v))
    }

    /// Where this profile's saves live: `<profile>/saves` when local saves are on, `None`
    /// when the player's own folder is used.
    pub fn saves_dir(&self) -> Option<PathBuf> {
        self.local_saves().then(|| self.profile.join("saves"))
    }

    /// Whether the profile keeps copies of the game's INI files [documented: MO2
    /// `Profile::localSettingsEnabled`, `settings.ini`'s `LocalSettings`]. A profile
    /// without the key is on when a `Fallout.ini` is there, since its copies exist only
    /// with local settings on.
    pub fn local_settings(&self) -> bool {
        self.profile_setting("LocalSettings").map_or_else(|| self.profile_ini(PROFILE_INIS[0]).is_some(), |v| bool_value(&v))
    }

    /// The profile's copy of the INI file `name`, matched without case (a profile copied
    /// from Windows into a case-sensitive file system may spell it differently).
    fn profile_ini(&self, name: &str) -> Option<PathBuf> {
        file_in(&self.profile, name)
    }

    /// The profile's own INI files, in the order the game reads them ([`PROFILE_INIS`]);
    /// empty unless local settings are on.
    pub fn profile_inis(&self) -> Vec<PathBuf> {
        if !self.local_settings() {
            return Vec::new();
        }
        PROFILE_INIS.iter().filter_map(|n| self.profile_ini(n)).collect()
    }

    /// The INI text the game reads under this profile, lowest precedence first: the
    /// profile's own INIs (local settings), then `initweaks.ini`, which MO2 rewrites from
    /// the enabled mods' INI tweaks in priority order and the profile's own tweaks, so a
    /// later file's key replaces an earlier one [documented: MO2
    /// `Profile::createTweakedIniFile`]. Empty when the profile keeps neither.
    pub fn ini_texts(&self) -> Vec<(PathBuf, String)> {
        let mut files = self.profile_inis();
        if let Some(p) = self.profile_ini(TWEAKS_INI) {
            files.push(p);
        }
        files.into_iter().filter_map(|p| std::fs::read(&p).ok().map(|b| (p, String::from_utf8_lossy(&b).into_owned()))).collect()
    }

    /// A setting as the game reads it under this profile: the value of `key` under
    /// `[section]` from the last of [`Layout::ini_texts`] that names it, with that file.
    pub fn ini_setting(&self, section: &str, key: &str) -> Option<(String, PathBuf)> {
        self.ini_texts().into_iter().rev().find_map(|(p, t)| ini_value(&t, section, key).map(|v| (v, p)))
    }

    /// Where a save of plugin `name` goes: the file of the enabled mod that gives `Data`
    /// its copy (the overwrite folder first, then the mods from the highest priority
    /// down), else a new file in the overwrite folder. A copy that only the game folder
    /// has is shadowed by one in overwrite, as MO2 itself does with a file a program
    /// changes there [hypothesis: usvfs' copy-on-write into overwrite].
    pub fn save_target(&self, name: &str) -> SaveTarget {
        let modlist = std::fs::read_to_string(self.profile.join("modlist.txt")).unwrap_or_default();
        let found = std::iter::once((None, self.overwrite.clone()))
            .chain(enabled_mods(&modlist).into_iter().map(|m| (Some(m.clone()), self.mods.join(m))))
            .find_map(|(m, dir)| file_in(&dir, name).map(|p| (m, p)));
        match found {
            Some((mod_name, path)) => SaveTarget { path, mod_name, exists: true },
            None => SaveTarget { path: self.overwrite.join(name), mod_name: None, exists: false },
        }
    }

    /// Turns plugin `name` on in the profile: a line in its `plugins.txt` (ANSI, CRLF, as
    /// MO2 writes it) and, when it has one, at the end of its `loadorder.txt` (UTF-8).
    /// `Ok(false)` when it was already on. MO2 reads both again when it refreshes after the
    /// program closes [hypothesis; observer-checks: the owner checks it shows ticked].
    pub fn turn_on(&self, name: &str) -> std::io::Result<bool> {
        let plugins = self.profile.join("plugins.txt");
        let bytes = match std::fs::read(&plugins) {
            Ok(b) => b,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => format!("{HEADER}\r\n").into_bytes(),
            Err(e) => return Err(e),
        };
        let on = parse(&bytes).unwrap_or_default().iter().any(|n| n.eq_ignore_ascii_case(name));
        if !on {
            let mut out = bytes;
            if !out.is_empty() && !out.ends_with(b"\n") {
                out.extend_from_slice(b"\r\n");
            }
            // Latin-1 when every character fits (the ANSI page's subset), else UTF-8.
            match name.chars().map(|c| u8::try_from(c as u32).ok()).collect::<Option<Vec<u8>>>() {
                Some(b) => out.extend(b),
                None => out.extend_from_slice(name.as_bytes()),
            }
            out.extend_from_slice(b"\r\n");
            std::fs::create_dir_all(&self.profile)?;
            std::fs::write(&plugins, out)?;
        }
        let order = self.profile.join("loadorder.txt");
        if let Ok(text) = std::fs::read_to_string(&order) {
            if !text.lines().any(|l| l.trim().eq_ignore_ascii_case(name)) {
                let mut t = text;
                if !t.is_empty() && !t.ends_with('\n') {
                    t.push_str("\r\n");
                }
                t.push_str(name);
                t.push_str("\r\n");
                std::fs::write(&order, t)?;
            }
        }
        Ok(!on)
    }
}

/// Where a plugin's save goes under MO2 ([`Layout::save_target`]).
#[derive(Debug, Clone, PartialEq)]
pub struct SaveTarget {
    pub path: PathBuf,
    /// The mod whose folder holds it; `None` for the overwrite folder.
    pub mod_name: Option<String>,
    /// Whether the file is there already.
    pub exists: bool,
}

/// The enabled mods of a profile's `modlist.txt`, highest priority first: lines `+Name`
/// are on, `-Name` off, `*Name` the game's own files MO2 does not manage; the file lists
/// the highest priority at the top [documented: MO2 `Profile::writeModlistNow` writes
/// the list in reverse priority; observed: the owner's profile, separators and all].
pub fn enabled_mods(modlist: &str) -> Vec<String> {
    modlist.lines().filter_map(|l| l.trim_end().strip_prefix('+')).filter(|n| !n.is_empty()).map(str::to_string).collect()
}

/// The file `name` directly in `dir`, matched without case (Windows paths are not
/// case-sensitive, a mod's file need not have the list's spelling), under its own name.
fn file_in(dir: &Path, name: &str) -> Option<PathBuf> {
    std::fs::read_dir(dir).ok()?.flatten().map(|e| e.path()).find(|p| p.is_file() && p.file_name().is_some_and(|f| f.to_string_lossy().eq_ignore_ascii_case(name)))
}

/// A QSettings bool: `true`/`false`, or MO2's numeric spelling (a `settings.ini` edited by
/// hand may hold either) [documented: Qt QSettings writes bools as `true`/`false`; observed:
/// MO2's profiles hold those] [hypothesis: `1`/`0` from a hand edit].
fn bool_value(v: &str) -> bool {
    matches!(v.trim().to_ascii_lowercase().as_str(), "true" | "1" | "yes")
}

/// A QSettings INI value with its escapes read: `\\`, `\"`, `\n`, `\t` and the other
/// one-letter escapes, `\x` and hex digits, `\0` and octal digits. Qt writes a character
/// outside printable ASCII that way, so a game folder such as `D:\Игры` or `C:\Users\José`
/// is stored as `\xd0\x98…` [hypothesis: QSettings' INI format, general knowledge; the
/// owner's instances show only `\\`, #1996]. In a `@ByteArray` (`bytes`) each escape is
/// one byte and the bytes are UTF-8 (Latin-1 when they are not); in a plain value it is
/// one character. The escape reads every hex (octal) digit that follows: Qt escapes a
/// digit right after one too, so where it ends is plain [hypothesis].
fn qt_unescape(v: &str, bytes: bool) -> String {
    let mut out: Vec<u8> = Vec::with_capacity(v.len());
    let put = |out: &mut Vec<u8>, c: char| out.extend_from_slice(c.encode_utf8(&mut [0; 4]).as_bytes());
    let mut chars = v.chars().peekable();
    while let Some(c) = chars.next() {
        if c != '\\' {
            put(&mut out, c);
            continue;
        }
        let Some(e) = chars.next() else { break };
        let radix = match e {
            'x' | 'X' => 16,
            '0'..='7' => 8,
            _ => {
                let lit = match e {
                    'n' => '\n',
                    't' => '\t',
                    'r' => '\r',
                    'a' => '\u{7}',
                    'b' => '\u{8}',
                    'f' => '\u{c}',
                    'v' => '\u{b}',
                    other => other,
                };
                put(&mut out, lit);
                continue;
            }
        };
        let mut n: u32 = if radix == 8 { e.to_digit(8).unwrap_or(0) } else { 0 };
        while let Some(d) = chars.peek().and_then(|c| c.to_digit(radix)) {
            n = n.saturating_mul(radix).saturating_add(d);
            chars.next();
        }
        match char::from_u32(n) {
            Some(_) if bytes && n <= 0xFF => out.push(n as u8),
            Some(c) => put(&mut out, c),
            None => {}
        }
    }
    match String::from_utf8(out) {
        Ok(s) => s,
        Err(e) => e.into_bytes().iter().map(|&b| b as char).collect(),
    }
}

