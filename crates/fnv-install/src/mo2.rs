/// Where MO2 puts its profile's `plugins.txt` for New Vegas: the Local AppData known
/// folder (`directories` reads the same known folder MO2 does), `FalloutNV\plugins.txt`.
pub fn plugins_file() -> Option<PathBuf> {
    directories::BaseDirs::new().map(|d| d.data_local_dir().join("FalloutNV").join("plugins.txt"))
}

/// The plugins of an MO2 `plugins.txt` in order, or `None` when the file is not MO2's (no
/// header line). Bytes that are not UTF-8 are read as Windows-1252's Latin-1 subset
/// [hypothesis: the ANSI code page of a Western-language Windows; other code pages would
/// mis-read non-ASCII names, which then show as missing].
pub fn parse(bytes: &[u8]) -> Option<Vec<String>> {
    let text = match std::str::from_utf8(bytes) {
        Ok(t) => t.to_string(),
        Err(_) => bytes.iter().map(|&b| b as char).collect(),
    };
    let text = text.strip_prefix('\u{feff}').unwrap_or(&text);
    let mut lines = text.lines();
    if lines.next()?.trim() != HEADER {
        return None;
    }
    let mut names: Vec<String> = Vec::new();
    for line in lines {
        let t = line.trim();
        if t.is_empty() || t.starts_with('#') {
            continue;
        }
        // Later games' lists mark active plugins with `*`; New Vegas' has none, but the
        // star is never part of a file name.
        let name = t.strip_prefix('*').unwrap_or(t).trim();
        if !name.is_empty() && !names.iter().any(|n| n.eq_ignore_ascii_case(name)) {
            names.push(name.to_string());
        }
    }
    Some(names)
}

/// What to load from MO2's list: its plugins present in `Data` (MO2's merged one), in its
/// order, `FalloutNV.esm` first. `None` when this start is not from MO2 or the file there
/// is not MO2's. NVForever's own list is neither read nor written.
pub fn sync(game: &GameInstall) -> Result<Option<(PathBuf, PluginSync)>, InstallError> {
    if !usvfs_loaded() {
        return Ok(None);
    }
    let Some(path) = plugins_file() else { return Ok(None) };
    let bytes = match std::fs::read(&path) {
        Ok(b) => b,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(InstallError::Io(path, e)),
    };
    let Some(names) = parse(&bytes) else { return Ok(None) };
    Ok(Some((path, load(&names, &data_plugins(game)?))))
}

/// MO2's active `names` against the plugins `present` in `Data`.
fn load(names: &[String], present: &[String]) -> PluginSync {
    let list = PluginList { entries: names.iter().map(|n| PluginEntry { name: n.clone(), active: true }).collect() };
    let (load, missing, base_forced) = list.load_order(present);
    PluginSync { load, from_mods: Vec::new(), added: Vec::new(), missing, base_forced, written: false, present: present.to_vec() }
}

/// A profile's plugins resolved to their files without MO2 running, for tools that read a
/// mod list headless (`fnvtool --mo2-profile`, issue #2275).
///
/// The profile folder is `<instance>\profiles\<name>`; its `plugins.txt` gives the active
/// plugins in load order ([`parse`]) and its `modlist.txt` the mods. `modlist.txt` has
/// one mod a line after MO2's header: `+name` an active mod, `-name` an inactive one
/// (separators too, `…_separator`), `*name` a file MO2 does not manage. The first line
/// is the highest priority [observed: the owner's Blue Moon profile, whose `[LATE]` mods
/// are at the top and its base `NVSE` mod at the bottom]. A plugin's file is taken from
/// the instance's `overwrite` folder, then from each active mod's folder
/// (`<instance>\mods\<name>`) in priority order, then from `data`, the game's Data folder,
/// as usvfs merges them [hypothesis: the default mods and overwrite folders; a
/// `mod_directory` or `overwrite_directory` setting in `ModOrganizer.ini` is not read].
/// Only plugins are resolved: a mod's loose files and archives are not merged.
pub fn profile_plugins(profile: &Path, data: &Path) -> Result<ProfilePlugins, InstallError> {
    let read = |p: PathBuf| std::fs::read(&p).map_err(|e| InstallError::Io(p, e));
    let names = parse(&read(profile.join("plugins.txt"))?).unwrap_or_default();
    let mods = modlist_active(&String::from_utf8_lossy(&read(profile.join("modlist.txt"))?));
    let instance = profile.parent().and_then(Path::parent).unwrap_or(profile);
    let mut roots: Vec<PathBuf> = vec![instance.join("overwrite")];
    roots.extend(mods.iter().map(|m| instance.join("mods").join(m)));
    roots.push(data.to_path_buf());
    let mut out = ProfilePlugins::default();
    for name in names {
        match roots.iter().map(|r| r.join(&name)).find(|p| p.is_file()) {
            Some(p) => out.found.push(p),
            None => out.missing.push(name),
        }
    }
    Ok(out)
}

/// What [`profile_plugins`] found: each plugin's file in load order, and the plugins no
/// mod nor the Data folder has.
#[derive(Debug, Default)]
pub struct ProfilePlugins {
    pub found: Vec<PathBuf>,
    pub missing: Vec<String>,
}

/// The active mods of a `modlist.txt`, highest priority first ([`profile_plugins`]).
fn modlist_active(text: &str) -> Vec<String> {
    text.lines().filter_map(|l| l.trim_end().strip_prefix('+')).filter(|n| !n.is_empty()).map(str::to_string).collect()
}

